-- Additive: existing password hashes, identities and business data are preserved.
ALTER TABLE users ADD COLUMN failed_login_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN failed_login_window TIMESTAMP(6);
ALTER TABLE users ADD COLUMN login_locked_until TIMESTAMP(6);
CREATE TABLE account_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 session_hash VARCHAR(64) NOT NULL UNIQUE,
 auth_version BIGINT NOT NULL,
 ip_address VARCHAR(64) NOT NULL, device_label VARCHAR(200) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, last_seen_at TIMESTAMP(6) NOT NULL,
 expires_at TIMESTAMP(6) NOT NULL, revoked_at TIMESTAMP(6)
);
CREATE INDEX idx_account_session_user ON account_sessions(user_id,revoked_at,expires_at);
CREATE TABLE account_security_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), type VARCHAR(32) NOT NULL,
 ip_address VARCHAR(64) NOT NULL, device_label VARCHAR(200) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_security_event_user ON account_security_events(user_id,created_at,id);
-- Pre-deployment sessions have no tracked session record and must log in again.
UPDATE users SET auth_version=auth_version+1;
