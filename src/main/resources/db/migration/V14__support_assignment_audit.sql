-- Append-only support assignment audit; no destructive migration.
CREATE TABLE support_assignment_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES support_tickets(id),
 old_assignee VARCHAR(100),
 new_assignee VARCHAR(100),
 actor VARCHAR(100) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_support_assignment_ticket
 ON support_assignment_events(ticket_id, created_at DESC, id DESC);
