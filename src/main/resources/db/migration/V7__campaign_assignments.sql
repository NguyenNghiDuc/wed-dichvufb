ALTER TABLE campaign_orders ADD COLUMN assignee_username VARCHAR(100);
CREATE INDEX idx_campaign_assignee ON campaign_orders(assignee_username, created_at);
CREATE TABLE campaign_assignment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES campaign_orders(id),
    old_assignee VARCHAR(100),
    new_assignee VARCHAR(100),
    actor VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_campaign_assignment_order ON campaign_assignment_events(campaign_id,created_at);
