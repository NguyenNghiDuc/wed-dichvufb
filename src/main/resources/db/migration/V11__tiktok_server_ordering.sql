CREATE TABLE tiktok_servers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, country VARCHAR(2) NOT NULL, description VARCHAR(500) NOT NULL,
 unit_price_vnd BIGINT NOT NULL CHECK(unit_price_vnd BETWEEN 1 AND 1000000),
 minimum_quantity INTEGER NOT NULL CHECK(minimum_quantity >= 1),
 maximum_quantity INTEGER NOT NULL CHECK(maximum_quantity >= minimum_quantity AND maximum_quantity <= 1000000),
 enabled BOOLEAN NOT NULL, version BIGINT NOT NULL
);
CREATE TABLE tiktok_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_username VARCHAR(100) NOT NULL,
 server_id BIGINT NOT NULL REFERENCES tiktok_servers(id), server_name VARCHAR(100) NOT NULL,
 country VARCHAR(2) NOT NULL, target_url VARCHAR(512) NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity > 0), unit_price_vnd BIGINT NOT NULL CHECK(unit_price_vnd > 0),
 total_price_vnd BIGINT NOT NULL CHECK(total_price_vnd > 0), note VARCHAR(1000) NOT NULL,
 status VARCHAR(24) NOT NULL, created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_tiktok_order_owner ON tiktok_orders(owner_username,created_at);
CREATE TABLE tiktok_order_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES tiktok_orders(id), actor VARCHAR(100) NOT NULL,
 status VARCHAR(24) NOT NULL, description VARCHAR(500) NOT NULL, created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_tiktok_events_order ON tiktok_order_events(order_id,created_at,id);
