-- PostgreSQL schema for a CLEAN production database. No automatic import of legacy H2 data.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  email VARCHAR(255),
  role VARCHAR(16) NOT NULL DEFAULT 'USER'
);
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_username VARCHAR(255),
  link_order VARCHAR(255),
  server_name VARCHAR(255),
  quantity INTEGER NOT NULL,
  note VARCHAR(255),
  price_per_unit INTEGER NOT NULL,
  total_price INTEGER NOT NULL,
  created_at TIMESTAMP(6)
);
CREATE INDEX idx_orders_owner ON orders(owner_username);
CREATE TABLE deposit_request (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_username VARCHAR(255),
  bank_name VARCHAR(255),
  account_number VARCHAR(255),
  amount BIGINT NOT NULL,
  note VARCHAR(255),
  status VARCHAR(255),
  created_at TIMESTAMP(6)
);
CREATE INDEX idx_deposit_owner ON deposit_request(owner_username);
CREATE TABLE bank_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bank_name VARCHAR(255),
  account_number VARCHAR(255),
  account_holder VARCHAR(255)
);
CREATE TABLE chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender VARCHAR(255),
  receiver VARCHAR(255),
  content VARCHAR(255) NOT NULL,
  "timestamp" TIMESTAMP(6)
);
CREATE TABLE campaign_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_username VARCHAR(100) NOT NULL,
  platform VARCHAR(20) NOT NULL,
  service_type VARCHAR(32) NOT NULL,
  target_url VARCHAR(512) NOT NULL,
  brief VARCHAR(1000) NOT NULL,
  quoted_price_vnd BIGINT NOT NULL,
  status VARCHAR(24) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_campaign_owner ON campaign_orders(owner_username);
CREATE TABLE campaign_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaign_orders(id),
  old_status VARCHAR(24),
  new_status VARCHAR(24) NOT NULL,
  actor VARCHAR(100) NOT NULL,
  description VARCHAR(500) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_campaign_events_order ON campaign_events(campaign_id,created_at);
CREATE TABLE account_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_username VARCHAR(100) NOT NULL,
  title VARCHAR(120) NOT NULL,
  message VARCHAR(500) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  read_at TIMESTAMP(6)
);
CREATE INDEX idx_notifications_owner ON account_notifications(owner_username,created_at);
