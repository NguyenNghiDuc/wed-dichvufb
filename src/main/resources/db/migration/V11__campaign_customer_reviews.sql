-- One private customer review per completed campaign.
CREATE TABLE campaign_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaign_orders(id),
  owner_username VARCHAR(100) NOT NULL,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  feedback VARCHAR(500) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_campaign_review_campaign UNIQUE (campaign_id)
);
CREATE INDEX idx_campaign_reviews_owner ON campaign_reviews(owner_username);
