-- New forward-only Flyway migration (V20-V25 reserved for another workstream).
-- An immutable credit per bank transfer and per deposit prevents double posting.
CREATE TABLE wallet_ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_username VARCHAR(100) NOT NULL,
 deposit_request_id BIGINT NOT NULL REFERENCES deposit_request(id),
 bank_transaction_id VARCHAR(100) NOT NULL,
 amount_vnd BIGINT NOT NULL CHECK (amount_vnd BETWEEN 1000 AND 1000000000),
 created_at TIMESTAMP(6) NOT NULL,
 CONSTRAINT uk_wallet_deposit UNIQUE (deposit_request_id),
 CONSTRAINT uk_wallet_bank_txn UNIQUE (bank_transaction_id)
);
CREATE INDEX idx_wallet_owner_created ON wallet_ledger(owner_username,created_at);
