CREATE TABLE system_broadcasts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(120) NOT NULL, message VARCHAR(500) NOT NULL,
 audience VARCHAR(16) NOT NULL CHECK(audience IN ('ALL','USER','STAFF','ADMIN')),
 status VARCHAR(16) NOT NULL CHECK(status IN ('DRAFT','SENT','CANCELLED')),
 created_by VARCHAR(100) NOT NULL, created_at TIMESTAMP(6) NOT NULL,
 acted_by VARCHAR(100), acted_at TIMESTAMP(6),
 recipient_count INTEGER NOT NULL DEFAULT 0 CHECK(recipient_count BETWEEN 0 AND 5000)
);
CREATE INDEX idx_broadcast_created ON system_broadcasts(created_at,id);
CREATE TABLE broadcast_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 broadcast_id BIGINT NOT NULL REFERENCES system_broadcasts(id),
 actor VARCHAR(100) NOT NULL, operation VARCHAR(16) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_broadcast_event ON broadcast_events(broadcast_id,created_at,id);
ALTER TABLE account_notifications ADD COLUMN broadcast_id BIGINT REFERENCES system_broadcasts(id);
ALTER TABLE account_notifications ADD CONSTRAINT uk_notification_broadcast_owner UNIQUE(broadcast_id,owner_username);
