CREATE TABLE coupon_uses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 coupon_id BIGINT NOT NULL REFERENCES coupons(id), order_id BIGINT NOT NULL UNIQUE REFERENCES campaign_orders(id),
 owner_username VARCHAR(100) NOT NULL, discount_vnd BIGINT NOT NULL CHECK(discount_vnd>0), created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_coupon_use_owner ON coupon_uses(coupon_id,owner_username);
CREATE TABLE coupon_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 coupon_id BIGINT NOT NULL REFERENCES coupons(id), actor VARCHAR(100) NOT NULL,
 operation VARCHAR(16) NOT NULL, created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_coupon_audit ON coupon_audit(coupon_id,created_at,id);
