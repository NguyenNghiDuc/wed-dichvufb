CREATE TABLE coupons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(32) NOT NULL UNIQUE,
 type VARCHAR(16) NOT NULL CHECK(type IN ('FIXED','PERCENT')), amount BIGINT NOT NULL CHECK(amount>0),
 maximum_discount_vnd BIGINT NOT NULL CHECK(maximum_discount_vnd BETWEEN 0 AND 50000000),
 minimum_order_vnd BIGINT NOT NULL CHECK(minimum_order_vnd BETWEEN 0 AND 50000000),
 maximum_uses INTEGER NOT NULL CHECK(maximum_uses BETWEEN 1 AND 100000),
 per_user_limit INTEGER NOT NULL CHECK(per_user_limit BETWEEN 1 AND 100 AND per_user_limit<=maximum_uses),
 used_count INTEGER NOT NULL CHECK(used_count BETWEEN 0 AND maximum_uses),
 starts_at TIMESTAMP(6) NOT NULL, ends_at TIMESTAMP(6) NOT NULL CHECK(ends_at>starts_at),
 enabled BOOLEAN NOT NULL, created_at TIMESTAMP(6) NOT NULL,
 CHECK((type='PERCENT' AND amount<=100) OR (type='FIXED' AND amount<=50000000))
);
CREATE INDEX idx_coupon_created ON coupons(created_at,id);
