CREATE TABLE service_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 campaign_order_id BIGINT REFERENCES campaign_orders(id),
 tiktok_order_id BIGINT REFERENCES tiktok_orders(id),
 owner_username VARCHAR(100) NOT NULL,
 rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 comment VARCHAR(1000) NOT NULL CHECK(length(comment) BETWEEN 10 AND 1000),
 created_at TIMESTAMP(6) NOT NULL,
 CONSTRAINT uk_review_campaign UNIQUE(campaign_order_id),
 CONSTRAINT uk_review_tiktok UNIQUE(tiktok_order_id),
 CONSTRAINT ck_review_one_order CHECK((campaign_order_id IS NOT NULL AND tiktok_order_id IS NULL) OR (campaign_order_id IS NULL AND tiktok_order_id IS NOT NULL))
);
CREATE INDEX idx_review_created ON service_reviews(created_at,id);
